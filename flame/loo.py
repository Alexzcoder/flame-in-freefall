"""Leave-one-out checks for the small target sets (too few cases to hold out whole test days).

  Solid fate (31 cases: BASS-II burned at the initial airflow and went out when the fan was turned down; SAFFIRE kept
  burning): a grid over the four knobs that decide survival (anchor, ign, cool, dif_o2), other knobs calibrated.
  Spread (7 NASA targets): a grid over the spread knobs.
For each case: pick the grid point with the lowest loss on all OTHER cases, then predict the left-out case. A case
counts as matched only if it is predicted without being seen.

    python -m flame.loo     # → dataset/loo_eval.md
"""
import itertools, os

import numpy as np

from flame import spread as SP
from flame.calibrate import datasets, simulate
from flame.media import ROOT
from flame.sim import load_theta

REPORT = os.path.join(ROOT, "dataset", "loo_eval.md")


def fate_loo(theta):
    cases = datasets()[2]
    grid = [{**theta, "anchor": a, "ign": i, "cool": c, "dif_o2": d}
            for a, i, c, d in itertools.product([0.2, 0.3, 0.4, 0.5], [0.35, 0.45, 0.55, 0.65], [0.3, 0.6, 1.2, 2.4],
                                                [0.06, 0.1, 0.16, 0.22])]
    alive, _ = simulate(cases, grid)
    burns = alive[:, :, -alive.shape[2] // 4:].mean(2) > 0.5  # (grid, case): same rule as calibrate.fate_loss
    truth = np.array([c["burns"] for c in cases])
    wrong = burns != truth  # (grid, case)
    hits = []
    for k in range(len(cases)):
        others = np.delete(wrong, k, axis=1)
        # loss on the others, burning and going-out halves weighted equally (as in calibrate.fate_loss)
        t = np.delete(truth, k)
        loss = 0.5 * others[:, t].mean(1) + 0.5 * others[:, ~t].mean(1)
        g = int(np.argmin(loss))
        hits.append(not wrong[g, k])
    return {"cases": len(cases), "loo_matched": int(sum(hits)), "fit_matched_best": int((~wrong).sum(1).max()),
            "by_case": {c["id"]: bool(h) for c, h in zip(cases, hits)}}


def spread_loo(theta):
    tau, fs = SP.scales()
    grid = [{**theta, "pyro": p, "c_thin": c, "k_strip": k, "burn_thin": b}
            for p, c, k, b in itertools.product([0.25, 0.35, 0.45], [0.05, 0.2, 0.8, 2.5], [2, 8, 30, 100],
                                                [0.01, 0.05, 0.2])]
    res = SP.run(grid, SP.TARGETS, tau, fs)  # [grid][target]
    def miss(r, tgt):
        if tgt[0] == "speed":
            return 1.0 if r["mm_s"] is None else min(1.0, abs(np.log(r["mm_s"] / tgt[1])) / np.log(3))
        return 0.0 if r["burns"] == tgt[1] else 1.0
    M = np.array([[miss(r, t[2]) for r, t in zip(row, SP.TARGETS)] for row in res])  # (grid, target)
    out = []
    for k, (name, _, tgt, src) in enumerate(SP.TARGETS):
        g = int(np.argmin(np.delete(M, k, axis=1).mean(1)))
        r = res[g][k]
        ok = (r["mm_s"] is not None and abs(np.log(r["mm_s"] / tgt[1])) <= np.log(tgt[2])) if tgt[0] == "speed" \
            else r["burns"] == tgt[1]
        out.append({"case": name, "nasa": tgt, "predicted": r, "matched": bool(ok)})
    best_fit = int(min(M.sum(1)))
    return {"targets": len(out), "loo_matched": sum(o["matched"] for o in out), "rows": out,
            "grid_best_total_miss": best_fit}


def main():
    theta = load_theta()
    f = fate_loo(theta)
    s = spread_loo(theta)
    L = ["# Leave-one-out checks", "", "Generated by `python -m flame.loo`. Each case is predicted by knobs chosen on all "
         "the other cases (grid search), so a match here is a prediction, not a fit.", "",
         f"## Solid fate: {f['loo_matched']} of {f['cases']} predicted correctly", "",
         "BASS-II flames that burned at the initial airflow and went out when the crew turned the fan down, and SAFFIRE "
         "flames that kept burning. Grid over anchor, ign, cool, dif_o2 (256 points).", "",
         "| Case | Predicted right |", "|---|---|"]
    L += [f"| {k} | {'yes' if v else 'no'} |" for k, v in f["by_case"].items()]
    L += ["", f"## Spread: {s['loo_matched']} of {s['targets']} predicted correctly", "",
          "Grid over pyro, c_thin, k_strip, burn_thin (144 points). Speeds count when within ×1.3.", "",
          "| Case | NASA | Predicted | Right |", "|---|---|---|---|"]
    for o in s["rows"]:
        t, r = o["nasa"], o["predicted"]
        nasa = f"{t[1]} mm/s" if t[0] == "speed" else ("burns" if t[1] else "goes out")
        pred = ("burns" if r["burns"] else "goes out") + (f", {r['mm_s']:.2f} mm/s" if r["mm_s"] else "")
        L.append(f"| {o['case']} | {nasa} | {pred} | {'yes' if o['matched'] else 'no'} |")
    L.append("")
    open(REPORT, "w").write("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
